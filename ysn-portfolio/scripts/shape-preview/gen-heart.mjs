// Offline generator for components/shapes/heart_data.ts. Run: node gen-heart.mjs
// The heart is the classic implicit surface
//   (x^2 + D y^2 + z^2 - 1)^3 - x^2 z^3 - (9/80) y^2 z^3 = 0   (z up, y depth)
// Rays from the centre find the surface, then farthest-point sampling keeps an
// evenly spread subset. That sampling is O(points * candidates), too heavy to
// run on every page load, so the result is baked into a small data file.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const N_POINTS = 500; // keep in sync with components/shapes/constants.ts
const CANDIDATES = 12000;
const DEPTH = 2.1; // higher = flatter heart
const GOLDEN_RATIO = (1 + Math.sqrt(5)) / 2;

const field = (x, y, z) => {
  const a = x * x + DEPTH * y * y + z * z - 1;
  return a * a * a - x * x * z * z * z - (9 / 80) * y * y * z * z * z;
};

const candidates = [];
for (let i = 0; i < CANDIDATES; i++) {
  const up = 1 - (2 * (i + 0.5)) / CANDIDATES;
  const ring = Math.sqrt(1 - up * up);
  const theta = (2 * Math.PI * i) / GOLDEN_RATIO;
  const d = [ring * Math.cos(theta), ring * Math.sin(theta), up];
  let lo = 0, hi = 2;
  for (let it = 0; it < 30; it++) {
    const mid = (lo + hi) / 2;
    if (field(d[0] * mid, d[1] * mid, d[2] * mid) < 0) lo = mid; else hi = mid;
  }
  const r = (lo + hi) / 2;
  // Screen space: x right, y down, z depth.
  candidates.push([d[0] * r, -d[2] * r, d[1] * r]);
}

// Farthest point sampling.
const dist = new Float64Array(CANDIDATES).fill(Infinity);
const picked = [];
let current = 0;
for (let k = 0; k < N_POINTS; k++) {
  const c = candidates[current];
  picked.push(c);
  dist[current] = -1;
  let best = -1, bestDist = -1;
  for (let i = 0; i < CANDIDATES; i++) {
    if (dist[i] < 0) continue;
    const q = candidates[i];
    const dd = (q[0] - c[0]) ** 2 + (q[1] - c[1]) ** 2 + (q[2] - c[2]) ** 2;
    if (dd < dist[i]) dist[i] = dd;
    if (dist[i] > bestDist) { bestDist = dist[i]; best = i; }
  }
  current = best;
}

// Centre and scale to a height of 1000 integer units (heart.ts rescales).
const ext = [0, 1, 2].map((a) => [Math.min(...picked.map((p) => p[a])), Math.max(...picked.map((p) => p[a]))]);
const scale = 1000 / (ext[1][1] - ext[1][0]);
const flat = picked.flatMap((p) => p.map((v, a) => Math.round((v - (ext[a][0] + ext[a][1]) / 2) * scale)));

const rows = [];
for (let i = 0; i < flat.length; i += 24) rows.push("  " + flat.slice(i, i + 24).join(",") + ",");
const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../components/shapes/heart_data.ts");
writeFileSync(
  out,
  `// Generated by scripts/shape-preview/gen-heart.mjs - do not edit by hand.\n` +
    `// ${N_POINTS} points on a 3D heart surface as flat x,y,z triples (height = 1000).\n` +
    `export const HEART_DATA: number[] = [\n${rows.join("\n")}\n];\n`,
);
console.log(`wrote ${out} (${picked.length} points)`);
